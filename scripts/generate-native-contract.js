#!/usr/bin/env node
'use strict';
// One machine-readable registry drives Swift method availability, argument
// validation and documented TypeScript/JSON contracts.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'scripts/native-capability-definitions.json'),'utf8'));
const types = JSON.parse(fs.readFileSync(path.join(root, 'scripts/native-contract-types.json'),'utf8'));
const generate = function generate(schema,types){
  if(schema.schemaVersion!==2||schema.protocolVersion!==2||!Array.isArray(schema.methods))throw Error("invalid bridge schema");
  const items=schema.methods.slice().sort((a,b)=>a.method.localeCompare(b.method));
  const valid=/^[A-Za-z][A-Za-z0-9]*\.[A-Za-z][A-Za-z0-9]*$/;
  const validTypes=new Set(["string","number","boolean","object","array"]);
  const validPermissions=new Set(["health","nfc","camera","microphone","contacts","calendar","reminders","bluetooth","motion","notifications","liveActivities","ai","spotlight","clipboard","photoLibrary","externalApps","files","biometrics","location","roadData","network","displayControl"]);
  const ids=new Set();
  for(const d of items){
    if(!valid.test(d.method)||ids.has(d.method))throw Error("bad/duplicate method "+d.method);
    ids.add(d.method);
    if(d.permission!=null&&!validPermissions.has(d.permission))throw Error("unknown permission "+d.method);
    if(!/^[0-9]{1,2}\.[0-9]{1,2}$/.test(d.minimumIOS))throw Error("invalid minimum iOS "+d.method);
    if(!Array.isArray(d.required))throw Error("required must be array "+d.method);
    for(const [n,t] of Object.entries(d.arguments||{})){if(!/^[A-Za-z][A-Za-z0-9]*$/.test(n)||!validTypes.has(t))throw Error("invalid argument "+d.method+"."+n);}
    if(d.required.some(n=>!Object.hasOwn(d.arguments||{},n)))throw Error("untyped required argument "+d.method);
  }
  if(items.length<135)throw Error("unexpected bridge surface reduction");
  const Q=JSON.stringify;
  const methods=items.map(x=>x.method);
  const pairMap=(filter,value,label)=>items.filter(filter).map(d=>`        ${Q(d.method)}: ${value(d)},`).join("\n");
  const permMap=pairMap(x=>x.permission,x=>Q(x.permission),"permission");
  const osMap=pairMap(x=>x.minimumIOS!=="16.0",x=>Q(x.minimumIOS),"os");
  const yes=(field)=>items.filter(x=>x[field]).map(x=>`        ${Q(x.method)},`).join("\n");
  const argMap=pairMap(x=>Object.keys(x.arguments||{}).length>0,x=>`[${Object.entries(x.arguments).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>`${Q(k)}: ${Q(v)}`).join(", ")}]`,"arg");
  const requiredMap=pairMap(x=>x.required.length>0,x=>`[${x.required.map(Q).join(", ")}]`,"required");
  const src=`// GENERATED by scripts/generate-native-contract.js from
// scripts/native-capability-definitions.json — do not edit manually.
import Foundation

/// Canonical names, permission mapping, typed argument shapes and runtime
/// metadata are all generated from one reviewed capability specification.
enum HTMLAppBridgeRegistry {
    static let protocolVersion = ${schema.protocolVersion}
    static let descriptorVersion = ${schema.descriptorVersion}
    static let methods: [String] = [
${methods.map(m=>"        "+Q(m)+",").join("\n")}
    ]
    static let methodSet = Set(methods)

    private static let permissions: [String: String] = [
${permMap}
    ]
    private static let minimumOS: [String: String] = [
${osMap}
    ]
    private static let userInitiatedMethods: Set<String> = [
${yes("userInitiated")}
    ]
    private static let cancellableMethods: Set<String> = [
${yes("nativeCancellation")}
    ]
    private static let argumentTypes: [String: [String: String]] = [
${argMap}
    ]
    private static let requiredArguments: [String: [String]] = [
${requiredMap}
    ]

    static func permission(for method: String) -> HTMLPermission? {
        guard let raw = permissions[method] else { return nil }
        return HTMLPermission(rawValue: raw)
    }

    static func describe(_ method: String) -> [String: Any]? {
        guard methodSet.contains(method) else { return nil }
        let doc = HTMLAppDeviceAPIResearch.entries.first { $0.id == method }
        return [
            "method": method,
            "protocolVersion": protocolVersion,
            "descriptorVersion": descriptorVersion,
            "available": true,
            "permission": permission(for: method)?.rawValue ?? "none",
            "title": doc?.title ?? method,
            "description": doc?.purpose ?? "Native HTMLApp operation; verify capability and authorization.",
            "usage": doc?.api ?? "",
            "constraints": doc?.constraints ?? "",
            "minimumIOS": minimumOS[method] ?? "16.0",
            "cancellable": cancellableMethods.contains(method),
            "userInitiationRecommended": userInitiatedMethods.contains(method),
            "argumentTypes": argumentTypes[method] ?? [:],
            "requiredArguments": requiredArguments[method] ?? [],
            "resultType": "unknown",
            "possibleErrors": [
                "invalid_arguments", "permission_denied",
                "unsupported_method", "cancelled", "native_timeout"
            ]
        ]
    }

    /// Validates known top-level argument shapes before executing native
    /// operations. Unknown optional keys remain allowed for compatibility;
    /// individual native services still validate ranges, quotas and paths.
    static func argumentIssue(method: String, arguments: [String: Any]) -> String? {
        guard methodSet.contains(method) else { return nil }
        for name in requiredArguments[method] ?? [] {
            if arguments[name] == nil {
                return "Native method \\(method) requires argument \\(name)."
            }
        }
        for (name, kind) in argumentTypes[method] ?? [:] {
            guard let value = arguments[name] else { continue }
            let correctType: Bool
            switch kind {
            case "string": correctType = value is String
            case "number": correctType = value is NSNumber || value is Double || value is Int
            case "boolean": correctType = value is Bool
            case "object": correctType = value is [String: Any]
            case "array": correctType = value is [Any]
            default: correctType = false
            }
            if !correctType {
                return "Native method \\(method) argument \\(name) must be \\(kind)."
            }
        }
        return nil
    }
}
`;
  const dts="// GENERATED from native-capability-definitions.json — do not edit manually.\n"+
    "export type HTMLAppNativeMethod =\n"+
    methods.map((m,i)=>"  | '"+m+"'"+(i===methods.length-1?";":"")).join("\n")+
    "\n"+types.join("\n");
  const json=JSON.stringify({schemaVersion:schema.schemaVersion,protocolVersion:schema.protocolVersion,
    descriptorVersion:schema.descriptorVersion,description:schema.description,methods,
    descriptors:Object.fromEntries(items.map(d=>[d.method,{
      minimumIOS:d.minimumIOS,permission:d.permission,
      userInitiationRecommended:d.userInitiated,nativeCancellation:d.nativeCancellation,
      arguments:d.arguments,requiredArguments:d.required,resultType:d.result
    }]))},null,2)+"\n";
  return {"HTMLAppV3/HTMLAppBridgeRegistry.swift":src,"docs/htmlapp-native-api.d.ts":dts,
    "docs/htmlapp-native-api.json":json};
};
const outputs = generate(schema, types);
for (const [filename, content] of Object.entries(outputs)) {
  const full = path.join(root, filename);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(full) || fs.readFileSync(full,'utf8') !== content)
      throw new Error(filename + ' is out of date. Run node scripts/generate-native-contract.js');
  } else {
    fs.mkdirSync(path.dirname(full), {recursive:true});
    fs.writeFileSync(full,content);
  }
}
console.log('Canonical native bridge schema synced with '+schema.methods.length+' methods.');
